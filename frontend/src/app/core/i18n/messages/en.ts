export type MessageKey = keyof typeof en;

/** What a translation has to provide: every key English has, and nothing it does not. */
export type Messages = Readonly<Record<MessageKey, string>>;

/** The base of a plural pair: `toolbar.problems` for `toolbar.problems.one` / `.other`. */
export type PluralKey = BaseOfPair<MessageKey>;

// A conditional distributes over a union only through a naked type parameter, hence the helper.
type BaseOfPair<K> = K extends `${infer Base}.other` ? Base : never;
